    if (cartoes().some(x => x.nome === 'Nubank Ana')) return;
    const k = uidNovo(), h = hoje(), m = N_mes(h), itens = [];
    enfileirar('salvar', { col: 'cartoes', item: { id: k, nome: 'Nubank Ana', fecha: 8, vence: 15, ativo: true, limite: 3000000 } });
