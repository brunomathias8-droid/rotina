    const g = uidNovo(); N_datasParcelas(h, 6).forEach((d, i) => itens.push({ id: uidNovo(), tipo: 'saida', forma: 'cartao', cartao: k, dia: d, v: 60000, desc: 'Geladeira', cat: 'compras', pago: true, parc: (i + 1) + '/6', grupo: g }));
