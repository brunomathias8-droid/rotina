// 3.11: Plano da família. A Luar propõe (simulada) e o casal aprova item por item; objetivos por horizonte com metas medidas;
// compromissos com dono e prazo (não cumprir exige motivo); ritual semanal passo a passo com ata; Hoje e lembretes. Roda depois do fluxo3.
const { chromium } = require('playwright');
const fs = require('fs');
const DIR = __dirname + '/fotos20/'; fs.mkdirSync(DIR, { recursive: true });
const erros = []; let n = 0;
const espera = ms => new Promise(r => setTimeout(r, ms));
function ok(c, m) { if (!c) { erros.push('FALHOU: ' + m); console.log('  ✗', m); } else console.log('  ✓', m); }
const luar = q => fetch('http://localhost:8787/__luar?' + q).then(r => r.json());
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'pt-BR', timezoneId: 'America/Fortaleza' });
  const p = await c.newPage();
  p.on('pageerror', e => erros.push('pageerror ' + e.message));
  p.on('console', m => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) erros.push('console ' + m.text()); });
  p.on('dialog', d => d.accept());
  const foto = async nome => { await espera(300); await p.screenshot({ path: DIR + String(++n).padStart(2, '0') + '-' + nome + '.png' }); };
  const fila = () => p.waitForFunction(() => S.fila.length === 0, null, { timeout: 20000 });
  await luar('chave=1');
  await p.goto('http://localhost:8787/'); await p.fill('#lnome', 'Bruno'); await p.fill('#lpin', '1234'); await p.click('button[type=submit]'); await p.waitForSelector('nav button');

  console.log('1. Aba Plano e a proposta da Luar');
  ok(await p.locator('nav button[data-v="plano"]').isVisible(), 'Plano está no menu de baixo');
  await p.click('nav button[data-v="plano"]'); await p.waitForSelector('#main h1');
  ok(await p.locator('#main button[data-a="planoLuar"]').isVisible(), 'plano vazio oferece "A Luar propõe"');
  await foto('vazio');
  await p.click('#main button[data-a="planoLuar"]');
  await p.locator('.sheet .h1', { hasText: 'Revisem e aprovem' }).waitFor({ timeout: 20000 });
  ok(await p.locator('.sheet .it', { hasText: 'Mês no azul vinte' }).isVisible() && await p.locator('.sheet .it', { hasText: 'Cancelar assinaturas vinte' }).isVisible(), 'proposta mostra objetivos, metas e compromissos');
  ok(await p.locator('.sheet .bolha b', { hasText: 'mais do que ganham' }).count() === 1, 'resumo da Luar no topo');
  await foto('proposta');
  await p.locator('.sheet .it', { hasText: 'Compromisso para descartar vinte' }).locator('button[data-a="propSel"]').click();
  await p.click('.sheet button[data-a="propAprovar"]'); await fila();
  const o = await p.evaluate(() => objetivosAtivos().filter(o => /vinte/.test(o.nome)).map(o => ({ id: o.id, nome: o.nome, horiz: o.horiz, dono: o.dono, metas: metasDe(o).map(m => m.nome + ':' + m.tipo + ':' + m.alvo) })));
  ok(o.length === 2 && o[0].horiz === 'curto' && o[1].horiz === 'medio', 'dois objetivos, um de curto e um de médio prazo');
  ok(o[0].metas.join() === 'Mês no azul vinte:saldo:0,Delivery vinte:reduzir:80000', 'metas ligadas ao objetivo (a de categoria inexistente ficou de fora): ' + o[0].metas.join());
  ok(await p.evaluate(() => S.pessoas.find(x => x.nome === 'Bruno').id) === o[1].dono, 'dono "Bruno" vira a pessoa');
  const cs = await p.evaluate(() => compAbertos().filter(c => /vinte/.test(c.texto)).map(c => c.texto + '|' + c.origem));
  ok(cs.length === 1 && cs[0] === 'Cancelar assinaturas vinte|luar', 'só o compromisso aprovado entrou');
  ok(!(await luar('contexto=1')).contexto.includes('proposta de plano sua esperando'), 'proposta some do servidor depois de aprovada');

  console.log('2. Tela do Plano');
  await p.evaluate(() => render(false)); await espera(300);
  ok(await p.locator('#main .sec', { hasText: 'Curto prazo' }).isVisible() && await p.locator('#main .sec', { hasText: 'Médio prazo' }).isVisible(), 'objetivos agrupados por horizonte');
  ok(await p.locator('#main .objetivo', { hasText: 'Fechar no azul vinte' }).locator('.tag').first().isVisible(), 'objetivo tem sinal (no rumo / em risco)');
  ok(await p.locator('#main .ritual-l', { hasText: 'Ritual da semana' }).isVisible() && await p.locator('#main .ritual-l', { hasText: 'Fechamento de' }).isVisible(), 'rituais semanal e mensal com data');
  await foto('plano');
  await p.locator('#main .objetivo', { hasText: 'Fechar no azul vinte' }).locator('.lst .it', { hasText: 'Mês no azul vinte' }).click(); await espera(300);
  ok(await p.locator('.sheet .h1', { hasText: 'Mês no azul vinte' }).isVisible() && await p.locator('.sheet', { hasText: 'Fechar o mês com sobra' }).isVisible(), 'meta "fechar no azul" abre com a previsão do mês');
  await p.click('.sheet [data-a="close"]');

  console.log('3. Compromissos: cumprir ou explicar');
  await p.evaluate(() => { enfileirar('salvar', { col: 'compromissos', item: { id: 'comp20venc01', texto: 'Levar marmita vinte', dono: 'ambos', prazo: N_somaDias(hoje(), -1), status: 'aberto', origem: 'app' } }); render(false); });
  await fila();
  ok(await p.locator('#main .it', { hasText: 'Levar marmita vinte' }).locator('.c-bad', { hasText: 'atrasado' }).isVisible(), 'compromisso vencido aparece atrasado');
  await p.locator('#main .it', { hasText: 'Cancelar assinaturas vinte' }).click();
  await p.click('.sheet button[data-a="compNaoAbre"]'); await p.fill('#f-motivo', 'ah');
  await p.click('.sheet button[data-a="compNao"]'); await espera(200);
  ok(await p.locator('#toast', { hasText: 'motivo de verdade' }).isVisible(), 'não cumprir sem motivo não passa');
  await p.fill('#f-motivo', 'Esqueci; vou pôr alarme no domingo'); await p.click('.sheet button[data-a="compNao"]'); await fila();
  ok(await p.evaluate(() => { const c = compromissos().find(c => c.texto === 'Cancelar assinaturas vinte'); return c.status === 'naofeito' && /alarme/.test(c.motivo); }), 'não cumprido fica registrado com o motivo');
  await p.click('#main button[data-k="comp"]:not([data-id])');
  await p.fill('#f-texto', 'Revisar plano do celular vinte'); await p.fill('#f-prazo', ''); await p.click('.sheet button[data-a="salvarComp"]'); await espera(200);
  ok(await p.locator('#toast', { hasText: 'sem prazo não é compromisso' }).isVisible(), 'compromisso sem prazo não passa');
  await p.click('.sheet [data-a="close"]');

  console.log('4. Ritual da semana, passo a passo');
  await p.click('#main .ritual-l:has-text("Ritual da semana") button[data-a="ritual"]'); await p.waitForSelector('.sheet .passos');
  ok(await p.locator('.sheet .h1', { hasText: 'Placar da semana' }).isVisible() && await p.locator('.sheet', { hasText: 'Mês no azul vinte' }).isVisible(), 'passo 1: placar com as metas');
  ok(await p.locator('.sheet button[data-a="ritLuar"]').isVisible(), 'dá para pedir a leitura da Luar');
  await p.click('.sheet button[data-a="ritLuar"]'); await p.locator('.sheet .bolha.luar').waitFor({ timeout: 15000 });
  await foto('ritual-placar');
  await p.click('.sheet button[data-a="ritPasso"][data-v="1"]');
  ok(await p.locator('.sheet .h1', { hasText: 'Prestação de contas' }).isVisible() && await p.locator('.sheet .panel', { hasText: 'Levar marmita vinte' }).isVisible(), 'passo 2: compromissos vencidos');
  await p.click('.sheet button[data-a="ritPasso"][data-v="1"]'); await espera(200);
  ok(await p.locator('#toast', { hasText: 'Falta dizer' }).isVisible(), 'não avança sem prestar contas');
  await p.locator('.sheet .panel', { hasText: 'Levar marmita vinte' }).locator('button[data-v="feito"]').click();
  await foto('ritual-contas');
  await p.click('.sheet button[data-a="ritPasso"][data-v="1"]');
  ok(await p.locator('.sheet .h1', { hasText: 'Compromissos da próxima etapa' }).isVisible(), 'passo 3: novos compromissos');
  await p.fill('#f-ntexto', 'Zero delivery seg a qui vinte'); await p.click('.sheet button[data-a="ritNovo"]');
  ok(await p.locator('.sheet .it', { hasText: 'Zero delivery seg a qui vinte' }).isVisible(), 'compromisso novo entra na lista');
  await p.click('.sheet button[data-a="ritPasso"][data-v="1"]');
  await p.fill('#f-notas', 'Decidimos cortar o delivery durante a semana.');
  await foto('ritual-fechar');
  await p.click('.sheet button[data-a="ritConcluir"]'); await fila();
  const rit = await p.evaluate(() => lista('rituais').find(r => r.tipo === 'semanal' && r.ref === refSemanal(hoje())));
  ok(rit && rit.ata.revisados.length === 1 && rit.ata.revisados[0].status === 'feito' && rit.ata.novos.length === 1 && /cortar o delivery/.test(rit.ata.notas) && rit.ata.luar, 'ata guarda placar, prestação de contas, novos, decisões e a leitura da Luar');
  ok(await p.evaluate(() => compromissos().find(c => c.id === 'comp20venc01').status) === 'feito', 'compromisso marcado como cumprido');
  ok(await p.evaluate(() => compAbertos().some(c => c.texto === 'Zero delivery seg a qui vinte' && c.origem === 'ritual')), 'novo compromisso aberto, vindo do ritual');
  ok(await p.locator('#main .ritual-l', { hasText: 'Ritual da semana' }).locator('button', { hasText: 'Ata' }).isVisible(), 'ritual aparece feito, com a ata');
  ok(await p.evaluate(() => sequenciaRituais()) === 1, 'sequência: 1 semana');
  await p.locator('#main .ritual-l', { hasText: 'Ritual da semana' }).locator('button', { hasText: 'Ata' }).click();
  ok(await p.locator('.sheet', { hasText: 'Decidimos cortar o delivery' }).isVisible(), 'ata abre com as decisões');
  await foto('ata');
  await p.click('.sheet [data-a="close"]');

  console.log('5. Luar, Hoje e lembretes');
  const ctx = (await luar('contexto=1')).contexto;
  ok(/## Plano da família/.test(ctx) && /Fechar no azul vinte/.test(ctx) && /NÃO CUMPRIU Cancelar assinaturas vinte .*alarme/.test(ctx) && /Ritual desta semana .*FEITO/.test(ctx), 'a Luar lê o plano, quem não cumpriu e por quê, e o ritual');
  await p.evaluate(() => { enfileirar('salvar', { col: 'compromissos', item: { id: 'comp20hoje01', texto: 'Ligar para o banco vinte', dono: S.eu, prazo: hoje(), status: 'aberto', origem: 'app' } }); S.tab = 'hoje'; render(false); });
  await fila();
  ok(await p.locator('#main .it', { hasText: 'Ligar para o banco vinte' }).isVisible(), 'Hoje mostra o compromisso que vence');
  await foto('hoje');
  const av = await fetch('http://localhost:8787/__avisos?hora=20&dia=2027-01-03').then(r => r.text());
  ok(/\[plano\] → Ritual da semana: agora/.test(av), 'domingo 20h: lembrete do ritual');
  ok(await p.evaluate(() => { const m = document.querySelector('#main'); return m.scrollWidth <= m.clientWidth + 1; }), 'sem rolagem lateral');
  await b.close();
  console.log(erros.length ? '\nPROBLEMAS:\n' + erros.join('\n') : '\nTudo certo, nenhum erro no console.');
})().catch(e => { console.error('ERRO', String(e).split('\n').slice(0, 3).join(' | ')); console.log(erros.join('\n')); process.exit(1); });
