// 3.6.2: marcar pago / não pago (inclusive pagamento de fatura). Roda depois do fluxo3 e do fluxo8 (C6 Bruno com fatura).
const { chromium } = require('playwright');
const fs = require('fs'); fs.mkdirSync(__dirname + '/fotos12', { recursive: true });
const erros = []; const ok = (c, m) => { if (!c) { erros.push(m); console.log('  ✗', m); } else console.log('  ✓', m); };
const espera = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const b = await chromium.launch(), c = await b.newContext({ viewport: { width: 900, height: 820 }, colorScheme: 'light' });
  await c.addInitScript(() => localStorage.setItem('rotina_estilo', 'editorial'));
  const p = await c.newPage(); p.on('pageerror', e => erros.push('pageerror ' + e.message)); p.on('dialog', d => d.accept());
  const fila = () => p.waitForFunction(() => S.fila.length === 0, null, { timeout: 20000 });
  await p.goto('http://localhost:8787/'); await p.fill('#lnome', 'Bruno'); await p.fill('#lpin', '1234'); await p.click('button[type=submit]'); await p.waitForSelector('nav button');
  const ctx = await p.evaluate(() => { const k = cartoes().find(x => x.nome === 'C6 Bruno'), ref = N_faturaRef(k, hoje()) ; const fo = fatura(k, N_somaMes(ref, -1)).total ? N_somaMes(ref, -1) : ref;
    if (!contasBancarias().length) enfileirar('salvar', { col: 'patrimonio', item: { id: uidNovo(), nome: 'Conta C6', classe: 'conta', nat: 'ativo', hist: [[hoje(), 2000000, new Date().toISOString()]], ativo: true } });
    return { k: k.id, ref: fo }; });
  await fila();
  const fat = () => p.evaluate(x => { const f = fatura(S.d.cartoes.get(x.k), x.ref); return { resta: f.resta, pagos: f.pagamentos.length, ag: f.agendados.length, n: lancs().filter(l => l.tipo === 'fatura' && l.cartao === x.k).length }; }, ctx);
  console.log('1. Pagar pela agenda');
  await p.evaluate(x => { S.tab = 'financas'; S.fv = 'contas'; S.mes = x.ref; render(false); }, ctx);
  await p.click(`#main button[data-a="pagar"][data-k="fatura"][data-id="${ctx.k}"]`); await espera(300);
  ok(await p.locator('.sheet .pagobox', { hasText: 'Já foi paga' }).isVisible(), 'pagamento de fatura agora tem "Já foi paga", logo abaixo do valor');
  await p.screenshot({ path: __dirname + '/fotos12/01-form.png' });
  await p.click('.sheet button[data-a="salvarLanc"]'); await fila();
  let f = await fat(); ok(f.resta === 0 && f.pagos === 1, 'fatura paga');
  console.log('2. "Não foi pago" na lista de pagas');
  await p.evaluate(() => render(false));
  await p.locator('#main details summary', { hasText: 'Pagas' }).click(); await espera(200);
  await p.screenshot({ path: __dirname + '/fotos12/02-pagas.png' });
  await p.click(`#main button[data-a="despagar"][data-k="fatura"][data-id="${ctx.k}"]`); await fila();
  f = await fat(); ok(f.resta > 0 && f.pagos === 0 && f.ag === 1, 'um toque: fatura volta para A pagar e o pagamento fica agendado');
  ok(await p.locator(`#main button[data-a="pagar"][data-k="fatura"][data-id="${ctx.k}"]`).isVisible(), 'aparece de novo em "A pagar"');
  await p.click(`#main button[data-a="pagar"][data-k="fatura"][data-id="${ctx.k}"]`); await fila();
  f = await fat(); ok(f.resta === 0 && f.n === 1, '"Pagar" marca o agendado como pago, sem criar um segundo pagamento');
  console.log('3. Pelo lançamento');
  const lid = await p.evaluate(x => lancs().find(l => l.tipo === 'fatura' && l.cartao === x.k).id, ctx);
  await p.evaluate(id => openSheet({ k: 'lanc', id }), lid); await espera(200);
  await p.click('.sheet .pagobox button.tog'); await p.click('.sheet button[data-a="salvarLanc"]'); await fila();
  f = await fat(); ok(f.ag === 1 && f.resta > 0, 'desligar "Já foi paga" no lançamento deixa a fatura em aberto');
  const conta = await p.evaluate(() => { const c = contasBancarias()[0]; return valorAtual(c); });
  await p.evaluate(x => openSheet({ k: 'fatura', id: x.k, v: x.ref }), ctx); await espera(200);
  ok(await p.locator('.sheet', { hasText: 'Pagamento agendado' }).isVisible(), 'a fatura mostra o pagamento agendado');
  await p.screenshot({ path: __dirname + '/fotos12/03-fatura-agendado.png' });
  await p.evaluate(() => closeSheet());
  await p.click(`#main button[data-a="pagar"][data-k="fatura"][data-id="${ctx.k}"]`); await fila();
  const conta2 = await p.evaluate(() => valorAtual(contasBancarias()[0]));
  ok(conta2 < conta, 'o dinheiro só sai da conta quando o pagamento é marcado como pago');
  console.log('4. Despesa comum');
  const did = await p.evaluate(() => { const id = uidNovo(); enfileirar('salvar', { col: 'lancamentos', item: { id, tipo: 'saida', v: 15000, dia: hoje(), desc: 'Conta de luz', cat: 'contas', forma: 'boleto', pago: true, carteira: contasBancarias()[0].id } }); return id; });
  await fila(); await p.evaluate(id => openSheet({ k: 'lanc', id }), did); await espera(200);
  ok(await p.locator('.sheet .pagobox', { hasText: 'Já foi pago' }).isVisible(), 'despesa comum também tem a chave no topo');
  await b.close(); console.log(erros.length ? 'PROBLEMAS\n' + erros.join('\n') : 'Tudo certo, nenhum erro no console.');
})();
